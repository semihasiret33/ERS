theta_df <- data.frame(theta_mean = c(0,0), theta_sd = c(1,1),
                       ers_mean = c(0, 0), ers_sd = c(1,1))

set.seed(112)
test1 <- generate(gen_model = "MNRM-Falk", N = 500000,
                  categories = 4, groups = 2,
