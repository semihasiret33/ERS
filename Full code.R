          split.screen(c(1,2))
          screen(1)
          plot(x = 1:20,
               y = as.numeric(MNRM_theta_bin_1), 
               type = "h",
               lwd = 3,
               ylab = "MNRM substantive trait bias",
               xlab = "True substantive trait",
