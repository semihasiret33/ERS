          } else{
            MNRM_colours_2[i] <- "red"
          }
          
          if(Tree_theta_bin_2[,i] < 0){
            Tree_colours_2[i] <- "blue"
          } else{
            Tree_colours_2[i] <- "red"
          }
        }
        
        if(plot_GPCM_only == TRUE){
